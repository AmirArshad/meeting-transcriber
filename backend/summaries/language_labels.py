def get_localized_labels(language: str = "en") -> Dict[str, Any]:
    """Return merged localized UI/Markdown labels for ``language``."""
    lang = language if language in LANGUAGE_LABELS else "en"
    row = LANGUAGE_LABELS[lang]
    base = dict(
        zip(
            (
                "title",
                "topics",
                "decisions",
                "action_items",
                "risks",
                "open_questions",
                "empty",
                "untitled",
                "profile",
                "model",
                "generated",
                "owner",
                "due",
                "timestamp",
                "timestamps",
            ),
            row,
        )
    )
    sections = dict(TEMPLATE_SECTION_LABELS.get(lang, TEMPLATE_SECTION_LABELS["en"]))
    fields = dict(TEMPLATE_FIELD_LABELS.get(lang, TEMPLATE_FIELD_LABELS["en"]))
    tag_names = dict(TAG_DISPLAY_LABELS.get(lang, TAG_DISPLAY_LABELS["en"]))
    return {
        **base,
        "tag": TAG_META_LABELS.get(lang, TAG_META_LABELS["en"]),
        "sections": sections,
        "fields": fields,
        "tag_names": tag_names,
    }
