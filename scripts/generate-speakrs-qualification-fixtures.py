#!/usr/bin/env python3
"""Generate synthetic speaker-qualification WAVs using an installed offline eSpeak NG.

Install eSpeak NG and its voice data separately. The shared library is discovered
with ctypes; use --library and --data-dir when it is not on the system search
path. The destination must be absent or empty. No audio is downloaded or sent
elsewhere. Example:

    python scripts/generate-speakrs-qualification-fixtures.py --output /tmp/speakrs-fixtures

These synthetic voices are not a substitute for consented natural-speech audio.
"""
from __future__ import annotations

import argparse
import audioop  # Python 3.11 is the supported project runtime.
import ctypes
import ctypes.util
import hashlib
import json
import struct
import sys
import wave
from pathlib import Path

TEXTS = (
    'Good morning. This is a synthetic recording made for a speaker identification test.',
    'Hello there. My voice is generated by a different offline speech setting for this experiment.',
    'We will discuss the delivery schedule and decide which tasks need attention this week.',
    'I can prepare the first report, and I will share a draft with the team on Friday.',
    'That sounds useful. Please include the open questions and the expected dates.',
    'Certainly. I will also list the risks and the people responsible for each item.',
    'Before we finish, let us confirm that the next meeting starts at ten in the morning.',
    'Agreed. Thank you everyone, and have a good afternoon.',
)
OUTPUT_RATE = 16000


def generate(output: Path, library: str | None, data_dir: str | None) -> None:
    library = library or ctypes.util.find_library('espeak-ng')
    if not library:
        raise RuntimeError('eSpeak NG shared library not found; install it or pass --library.')
    if output.exists() and (not output.is_dir() or any(output.iterdir())):
        raise RuntimeError('Output directory must be absent or empty.')
    output.mkdir(parents=True, exist_ok=True)
    engine = ctypes.CDLL(library)
    engine.espeak_Initialize.argtypes = [ctypes.c_int, ctypes.c_int, ctypes.c_char_p, ctypes.c_int]
    engine.espeak_Initialize.restype = ctypes.c_int
    rate = engine.espeak_Initialize(2, 0, str(data_dir).encode() if data_dir else None, 0)
    if rate <= 0:
        raise RuntimeError('eSpeak NG initialization failed; check the installed voice data or --data-dir.')
    callback_type = ctypes.CFUNCTYPE(ctypes.c_int, ctypes.POINTER(ctypes.c_short), ctypes.c_int, ctypes.c_void_p)
    chunks: list[bytes] = []

    @callback_type
    def capture(samples, count, _events):
        if samples and count:
            chunks.append(ctypes.string_at(samples, count * 2))
        return 0

    engine.espeak_SetSynthCallback.argtypes = [callback_type]
    engine.espeak_SetSynthCallback(capture)
    engine.espeak_SetVoiceByName.argtypes = [ctypes.c_char_p]
    engine.espeak_SetVoiceByName.restype = ctypes.c_int
    engine.espeak_SetParameter.argtypes = [ctypes.c_int, ctypes.c_int, ctypes.c_int]
    engine.espeak_Synth.argtypes = [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_uint, ctypes.c_int,
                                   ctypes.c_uint, ctypes.c_uint, ctypes.c_void_p, ctypes.c_void_p]
    engine.espeak_Synchronize.argtypes = []
    clips = []
    for index, text in enumerate(TEXTS):
        chunks.clear()
        voice = b'en-us+m3' if index % 2 == 0 else b'en-us+f3'
        if engine.espeak_SetVoiceByName(voice) != 0:
            raise RuntimeError('Required English eSpeak NG voice or variant is unavailable.')
        engine.espeak_SetParameter(1, 158 if index % 2 == 0 else 172, 0)
        engine.espeak_SetParameter(3, 40 if index % 2 == 0 else 68, 0)
        raw = text.encode('utf-8') + b'\0'
        if engine.espeak_Synth(raw, len(raw), 0, 1, 0, 1, None, None) != 0:
            raise RuntimeError('eSpeak NG synthesis failed.')
        engine.espeak_Synchronize()
        pcm = b''.join(chunks)
        if not pcm or len(pcm) % 2:
            raise RuntimeError('eSpeak NG returned invalid audio.')
        # eSpeak returns native-endian int16 samples.
        values = struct.unpack(f'={len(pcm) // 2}h', pcm)
        clips.append(values)

    for name, repetitions in (('short', 1), ('long', 4)):
        samples: list[int] = []
        turns = []
        for _ in range(repetitions):
            for index, clip in enumerate(clips):
                overlap = int(rate * 0.6) if index == 3 else 0
                gap = int(rate * 0.3) if not overlap and samples else 0
                start = len(samples) + gap - overlap
                if gap:
                    samples.extend([0] * gap)
                if overlap:
                    for offset in range(overlap):
                        samples[start + offset] = max(-32768, min(32767, samples[start + offset] + clip[offset]))
                    samples.extend(clip[overlap:])
                else:
                    samples.extend(clip)
                turns.append({'speaker': 'A' if index % 2 == 0 else 'B',
                              'start': round(start / rate, 3), 'end': round((start + len(clip)) / rate, 3),
                              'overlap_previous': bool(overlap), 'text': TEXTS[index]})
        native_pcm = struct.pack(f'<{len(samples)}h', *samples)
        pcm, _ = audioop.ratecv(native_pcm, 2, 1, rate, OUTPUT_RATE, None)
        wav_path = output / f'{name}.wav'
        with wave.open(str(wav_path), 'wb') as wav:
            wav.setnchannels(1)
            wav.setsampwidth(2)
            wav.setframerate(OUTPUT_RATE)
            wav.writeframes(pcm)
        with wave.open(str(wav_path), 'rb') as wav:
            if (wav.getnchannels(), wav.getsampwidth(), wav.getframerate()) != (1, 2, OUTPUT_RATE):
                raise RuntimeError('Generated WAV format verification failed.')
            frames = wav.getnframes()
            actual_pcm = wav.readframes(frames)
        if actual_pcm != pcm or abs(frames / OUTPUT_RATE - len(samples) / rate) > 1 / OUTPUT_RATE:
            raise RuntimeError('Generated WAV contents or duration verification failed.')
        manifest = {'generator': 'offline eSpeak NG; synthetic voices', 'sample_rate': OUTPUT_RATE,
                    'duration': round(frames / OUTPUT_RATE, 3), 'sha256': hashlib.sha256(wav_path.read_bytes()).hexdigest(),
                    'turns': turns}
        (output / f'{name}.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
        print(f'{name}: {manifest["duration"]} seconds, {len(turns)} synthetic turns, sha256 {manifest["sha256"]}')


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True, type=Path, help='Absent or empty destination directory')
    parser.add_argument('--library', help='eSpeak NG shared library path or loader name')
    parser.add_argument('--data-dir', help='Directory containing espeak-ng-data')
    args = parser.parse_args()
    try:
        generate(args.output, args.library, args.data_dir)
    except (OSError, RuntimeError, ValueError) as error:
        print(f'Fixture generation failed: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
